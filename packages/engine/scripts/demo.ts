import { formatMoney } from '../src/simulate.js';
import { forecast } from '../src/forecast.js';
import { generateOptions } from '../src/options.js';
import { simulate } from '../src/simulate.js';
import { getSeedForecastInput } from '../test-support/fixturesData.js';
import { seedSnapshot } from '../test-support/seedScenario.js';

function padL(str: string, len: number): string {
  return str.padStart(len);
}

function padR(str: string, len: number): string {
  return str.padEnd(len);
}

export function runDemo(): void {
  const seedInput = getSeedForecastInput();
  const baseline = forecast(seedInput);

  console.log('========================================================================================');
  console.log('                          SYSTEM 2: CASH ENGINE DEMO RUN                                ');
  console.log('========================================================================================');
  console.log(`Business: ${seedSnapshot.business.name} | As Of: ${seedSnapshot.business.asOf}`);
  console.log(`Starting Balance: ${formatMoney(seedSnapshot.business.startingBalance)} | Reserve Threshold: ${formatMoney(seedSnapshot.business.reserveThreshold)}`);
  console.log('----------------------------------------------------------------------------------------\n');

  console.log('--- (A) BASELINE 30-DAY CASH FORECAST ---');
  console.log('----------------------------------------------------------------------------------------');
  console.log(
    `${padR('Day', 5)} | ${padR('Date', 10)} | ${padL('Receipts', 12)} | ${padL('Outflows', 12)} | ${padL('Closing', 14)} | ${padR('Breach?', 8)} | ${padR('Notes', 24)}`,
  );
  console.log('----------------------------------------------------------------------------------------');

  for (let t = 0; t < baseline.days.length; t++) {
    const day = baseline.days[t]!;
    let note = '';
    if (day.date === '2026-11-04') {
      note = 'Supplier Obligation ($2k)';
    } else if (day.date === '2026-11-06') {
      note = '*** PAYROLL BREACH ***';
    } else if (day.date === '2026-11-10') {
      note = 'Inv-002 Collected';
    } else if (day.date === '2026-11-20') {
      note = 'Rent Lease ($1.5k)';
    }

    const breachMarker = day.belowReserve ? 'YES (<R)' : 'No';

    console.log(
      `${padR(String(t + 1), 5)} | ${padR(day.date, 10)} | ${padL(formatMoney(day.receipts), 12)} | ${padL(formatMoney(day.outflows), 12)} | ${padL(formatMoney(day.closing), 14)} | ${padR(breachMarker, 8)} | ${padR(note, 24)}`,
    );
  }

  console.log('----------------------------------------------------------------------------------------');
  console.log(`Baseline Summary: Lowest Balance: ${formatMoney(baseline.lowest.amount)} on ${baseline.lowest.date} | Shortfall: ${formatMoney(baseline.shortfall)}`);
  console.log(`First Reserve Breach: ${baseline.firstBreachDate ?? 'None'}`);
  console.log('----------------------------------------------------------------------------------------\n');

  console.log('--- (B) AR INTERVENTION SCENARIOS (GENERATED BY ENGINE) ---');
  console.log('----------------------------------------------------------------------------------------');
  console.log(
    `${padR('Option', 8)} | ${padR('Type & Target', 28)} | ${padL('Lowest Delta', 14)} | ${padL('Cash Cost', 12)} | ${padR('Closes Gap?', 11)} | ${padR('Primary Assumption', 40)}`,
  );
  console.log('----------------------------------------------------------------------------------------');

  // Option 1: REMIND on largest overdue (inv_001)
  const inv1 = seedSnapshot.invoices.find((i) => i.id === 'inv_001')!;
  const payer1 = seedSnapshot.payers.find((p) => p.id === inv1.payerId)!;
  const options1 = generateOptions(seedInput, inv1, payer1, seedSnapshot.policy);
  const opt1 = options1.find((o) => o.type === 'REMIND')!;
  const sim1 = simulate(seedInput, opt1);

  // Option 2: OFFER_DISCOUNT 3% on 2nd largest overdue (inv_002)
  const inv2 = seedSnapshot.invoices.find((i) => i.id === 'inv_002')!;
  const payer2 = seedSnapshot.payers.find((p) => p.id === inv2.payerId)!;
  const options2 = generateOptions(seedInput, inv2, payer2, seedSnapshot.policy);
  const opt2 = options2.find((o) => o.type === 'OFFER_DISCOUNT' && o.discountPct === 3)!;
  const sim2 = simulate(seedInput, opt2);

  // Option 3: OFFER_INSTALMENTS 2 on 3rd largest overdue (inv_003)
  const inv3 = seedSnapshot.invoices.find((i) => i.id === 'inv_003')!;
  const payer3 = seedSnapshot.payers.find((p) => p.id === inv3.payerId)!;
  const options3 = generateOptions(seedInput, inv3, payer3, seedSnapshot.policy);
  const opt3 = options3.find((o) => o.type === 'OFFER_INSTALMENTS' && o.count === 2)!;
  const sim3 = simulate(seedInput, opt3);

  const optionsList = [
    { label: 'Opt 1', name: `REMIND (inv_001)`, sim: sim1 },
    { label: 'Opt 2', name: `DISCOUNT 3% (inv_002)`, sim: sim2 },
    { label: 'Opt 3', name: `INSTALMENTS x2 (inv_003)`, sim: sim3 },
  ];

  for (const { label, name, sim } of optionsList) {
    const closesGapStr = sim.closesGap ? 'YES' : 'No';
    const mainAssumption = sim.assumptions[sim.assumptions.length - 1] ?? '';
    console.log(
      `${padR(label, 8)} | ${padR(name, 28)} | ${padL(formatMoney(sim.lowestDelta), 14)} | ${padL(formatMoney(sim.cashCost), 12)} | ${padR(closesGapStr, 11)} | ${padR(mainAssumption, 40)}`,
    );
  }
  console.log('----------------------------------------------------------------------------------------');
}

runDemo();

