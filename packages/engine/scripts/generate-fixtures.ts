import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateAllFixtures } from '../test-support/fixturesData.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const fixturesDir = path.resolve(__dirname, '../fixtures');

mkdirSync(fixturesDir, { recursive: true });

const fixtures = generateAllFixtures();

for (const [filename, content] of Object.entries(fixtures)) {
  const filePath = path.join(fixturesDir, filename);
  writeFileSync(filePath, content, 'utf-8');
  console.log(`Generated fixture: ${filename}`);
}

const readmeContent = `# Engine Fixtures

These fixtures represent reproducible golden inputs and outputs computed by System 2 Cash Engine from the canonical seed scenario (\`test-support/seedScenario.ts\`).

> **NOTICE**: These files are automatically generated by running \`pnpm run fixtures\` (executing \`scripts/generate-fixtures.ts\`). Do not hand-edit these files.

## Files & Data Shapes

| File | Shape | Description |
|---|---|---|
| \`seed-snapshot.json\` | \`Snapshot\` | Canonical demo snapshot containing business balance, payers, invoices, obligations, and policy. |
| \`seed-input.json\` | \`ForecastInput\` | Input passed to the cash engine, including projected expected receipts over a 30-day horizon. |
| \`forecast.baseline.json\` | \`ForecastResult\` | Baseline 30-day cash flow forecast showing the payroll breach on Friday (2026-11-06). |
| \`simulate.option-1.json\` | \`ScenarioComparison\` | Counterfactual comparison simulating \`REMIND\` on the largest overdue invoice (\`inv_001\`). |
| \`simulate.option-2.json\` | \`ScenarioComparison\` | Counterfactual comparison simulating \`OFFER_DISCOUNT\` (3%) on the 2nd largest overdue invoice (\`inv_002\`). |
| \`simulate.option-3.json\` | \`ScenarioComparison\` | Counterfactual comparison simulating \`OFFER_INSTALMENTS\` (2 instalments) on the 3rd largest overdue invoice (\`inv_003\`). |
`;

writeFileSync(path.join(fixturesDir, 'README.md'), readmeContent, 'utf-8');
console.log('Generated fixtures/README.md');

