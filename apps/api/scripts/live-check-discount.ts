import { buildApp } from '../src/app.js';
import { runMigrations } from '../src/db/migrate.js';
import { closeDb } from '../src/db/index.js';
import { resetCachedEnv } from '../src/config/env.js';
import { resetAgentInstance } from '../src/adapters/agent.js';
import { resetEngineInstance } from '../src/adapters/engine.js';
import { InvoiceRepository, ActionRecordRepository } from '../src/db/repositories.js';
import { PayPalClient } from '../src/paypal/client.js';

async function main() {
  process.env.ENGINE_IMPL = 'real';
  process.env.AGENT_IMPL = 'real';
  process.env.POLICY_IGNORE_QUIET_HOURS = 'true';
  process.env.DATABASE_URL = process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5433/settle';

  resetCachedEnv();
  resetEngineInstance();
  resetAgentInstance();

  console.log('=== Step 1: Running Migrations on PostgreSQL (port 5433) ===');
  await runMigrations();

  console.log('\n=== Step 2: Initializing API Application with Real PayPal Client ===');
  const app = await buildApp();
  await app.ready();
  const paypalClient = new PayPalClient({});

  console.log('\n=== Step 3: POST /api/demo/reset ===');
  const resetRes = await app.inject({
    method: 'POST',
    url: '/api/demo/reset',
  });
  console.log(`Reset status: ${resetRes.statusCode}`);

  console.log('\n=== Step 4: POST /api/demo/provision-paypal ===');
  const provRes = await app.inject({
    method: 'POST',
    url: '/api/demo/provision-paypal',
  });
  console.log(`Provision status: ${provRes.statusCode}`);
  const provBody = JSON.parse(provRes.payload);
  console.log(`Provisioned ${provBody.provisioned?.length || 0} invoices.`);

  console.log('\n=== Step 5: POST /api/agent/run (Run Agent Once) ===');
  const runRes = await app.inject({
    method: 'POST',
    url: '/api/agent/run',
    payload: {},
  });
  console.log(`Agent run status: ${runRes.statusCode}`);
  const runBody = JSON.parse(runRes.payload);
  console.log(`Generated ${runBody.actions?.length || 0} actions.`);

  // Find the OFFER_DISCOUNT action for inv_001
  const actionRepo = new ActionRecordRepository();
  const invoiceRepo = new InvoiceRepository();
  const inv1 = await invoiceRepo.getById('inv_001');
  console.log(`inv_001 before approval: nominal amount=${inv1?.amount}, discountPct=${inv1?.discountPct ?? 0}, paypalInvoiceId=${inv1?.paypalInvoiceId}`);

  let discountAction = runBody.actions?.find(
    (a: any) => a.invoiceId === 'inv_001' && a.type === 'OFFER_DISCOUNT',
  );

  if (!discountAction) {
    // If not generated by agent run (e.g. if rules or model selected different action), insert one
    console.log('Inserting OFFER_DISCOUNT action for inv_001...');
    discountAction = {
      id: `act_disc_${Date.now()}`,
      invoiceId: 'inv_001',
      type: 'OFFER_DISCOUNT',
      params: { discountPct: 2 },
      reason: 'Offer 2% prompt-pay discount to bridge cash deficit',
      policy: { allowed: true, requiresApproval: true, violations: [] },
      status: 'AWAITING_APPROVAL',
      createdAt: new Date().toISOString(),
    };
    await actionRepo.insert(discountAction);
  }

  console.log(`\n=== Step 6: Approve inv_001 discount action (${discountAction.id}) ===`);
  const approveRes = await app.inject({
    method: 'POST',
    url: `/api/actions/${discountAction.id}/approve`,
  });
  console.log(`Approve status: ${approveRes.statusCode}`);
  const approvedAction = JSON.parse(approveRes.payload);
  console.log(`Action status after approval: ${approvedAction.status}`);

  const inv1AfterDiscount = await invoiceRepo.getById('inv_001');
  console.log(`inv_001 after approval: nominal amount=${inv1AfterDiscount?.amount}, discountPct=${inv1AfterDiscount?.discountPct}, dueDate=${inv1AfterDiscount?.dueDate}`);

  console.log('\n=== Step 7: POST /api/demo/simulate-payment { invoiceId: "inv_001" } ===');
  const payRes = await app.inject({
    method: 'POST',
    url: '/api/demo/simulate-payment',
    payload: { invoiceId: 'inv_001' },
  });
  console.log(`Simulate payment status: ${payRes.statusCode}`);
  const payBody = JSON.parse(payRes.payload);
  console.log('Payment result:', {
    status: payBody.status,
    invoiceStatus: payBody.invoice?.status,
    invoiceAmountPaid: payBody.invoice?.amountPaid,
    delta: payBody.delta,
    newCashBalance: payBody.newCashBalance,
  });

  console.log('\n=== Step 8: GET /api/dashboard (Check KPIs) ===');
  const dashRes = await app.inject({
    method: 'GET',
    url: '/api/dashboard',
  });
  console.log(`Dashboard status: ${dashRes.statusCode}`);
  const dashBody = JSON.parse(dashRes.payload);
  console.log('=== KPI Summary ===');
  console.log(`  Cash:             ${dashBody.kpis?.cash} cents ($${(dashBody.kpis?.cash / 100).toFixed(2)}) [Expected: 1323000]`);
  console.log(`  Shortfall:        ${dashBody.kpis?.shortfall} cents ($${(dashBody.kpis?.shortfall / 100).toFixed(2)}) [Expected: 0]`);
  console.log(`  Overdue Total:    ${dashBody.kpis?.overdueTotal} cents ($${(dashBody.kpis?.overdueTotal / 100).toFixed(2)})`);
  console.log(`  First Breach:     ${dashBody.forecast?.firstBreachDate ?? 'None'}`);

  console.log('\n=== Step 9: Query Live PayPal Sandbox Invoice Details ===');
  if (inv1AfterDiscount?.paypalInvoiceId) {
    const livePP = await paypalClient.getInvoice(inv1AfterDiscount.paypalInvoiceId);
    console.log('Live PayPal invoice representation:');
    console.log(`  PayPal Invoice ID: ${inv1AfterDiscount.paypalInvoiceId}`);
    console.log(`  Status:            ${livePP.status}`);
    console.log(`  Total:             ${livePP.total} cents ($${livePP.total ? (livePP.total / 100).toFixed(2) : '0.00'})`);
    console.log(`  Amount Paid:       ${livePP.amountPaid} cents ($${(livePP.amountPaid / 100).toFixed(2)})`);
    console.log(`  Amount Due:        ${livePP.amountDue ?? 0} cents ($${livePP.amountDue ? (livePP.amountDue / 100).toFixed(2) : '0.00'})`);
  }

  await app.close();
  await closeDb();
  console.log('\n=== Live Check Complete ===');
}

main().catch((err) => {
  console.error('Live check failed:', err);
  process.exit(1);
});
